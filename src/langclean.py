"""语料语言清洗 —— 剥掉「中文正文 + 日文原文」型条目的日文尾巴。

⚠️ **为什么在 src/ 而不是写成一次性的 UPDATE 脚本**：文本的源头是 dump，
   而 `load_profiles.py` / `build_char_chunks.py` 每次重跑都从 dump 重新写库。
   做成一次性 UPDATE 的话，**下次任何人重跑 loader，日文就原样写回来，且不报错** ——
   与「series_root.json 不入 git」「jieba 词典漂移」「%.7g vs %.9g」同一族故障：
   本地好好的，换机器/重灌就静默地错。
   ⇒ 清洗必须是**管道的一部分**，两个 loader 写库前都调它。

📌 背景（CLAUDE.md 第四部分「日语语料」）：实测 10,740 条作品简介里
   37.2% 是纯日文、5.1% 是中日混排；角色 chunk 里 63.4% 纯日文、1.7% 混排。
   **本模块只处理"混排"那一档**（零成本，纯字符串操作）；
   纯日文那批只能靠翻译，是独立的一步。

实测可剥（2026-08-16 干跑）：
   anime_profile.summary   477 条（标记 378 · 分块 99）· 250,836 → 107,251 字
   plot_chunk.text         119 条（标记 119 · 分块  0）·  20,669 →   8,124 字

⚠️ **改动本模块会改变语料文本 → 改变 embedding 缓存键 → 需要重新花钱编码。**
   与 parse_moegirl.py 的切分规则同一条纪律。
"""

from __future__ import annotations

import re

# 平假名 + 片假名。⚠️ **不含汉字** —— 中日共用汉字，拿汉字判语言必然误判。
KANA = re.compile(r"[ぁ-んァ-ヶ]")

# 「原文」分隔标记。⚠️ 写法不止一种，实测见过半角/全角方括号两种。
MARK = re.compile(r"[\[【]\s*(简介原文|原文|日文简介|日文原文)\s*[\]】]")

# ── 三道安全阀，宁可漏剥不可错剥 ──────────────────────────────
# ⚠️ **MIN_KEEP 不能定高。** 首版写的 40，实测把 29 条**干净中文**的角色简介
#    整条放弃了 —— 「安托姆格盗贼公会副会长。」12 字、
#    「伊豆大学一年级生。眉毛全部剃光，外表凶狠但存在感稀薄，常会被人遗忘。」34 字，
#    都是完整可用的描述。这正是 E.8 / F.3 已经记过两次的教训：
#    **「短不等于没用」「长度是错的判据」**（F.3 的「结果≥4字」曾把
#    `幸运星 OVA → 幸运星` 一起杀掉）。
#    ⇒ 真正的判据是 MAX_KANA（头部是不是干净中文）；
#      长度下限只用来挡「标记出现在开头、头部实际为空」这类退化情况。
MIN_KEEP = 8
MAX_KANA = 0.05    # 剩余允许的假名率 —— 语言判据
BLOCK_JP = 0.08    # 判定一个段落为「日文块」的假名率阈值

# ⚠️ **比例守卫：剥完必须保留原文的 15% 以上。** 这道阀防的是另一类误剥 ——
#    「一句中文备注 + 日文正文」，实测：
#        《东京喰种√A》 449→10 字  只剩宣传语「悲劇、2周目。」
#        《金刚狼》     437→15 字  只剩「Marvel作品动画化第二弹。」
#        《DOG DAYS》  669→29 字  只剩一句梗概
#    这类里日文**不是**中文的原文，而是真正的内容主体。剥掉它是双重损失：
#    丢内容，而且剥完变成"干净中文"，翻译那一步就不会再管它了。
#
# ⚠️ **阈值 0.15 是实测定的，两个语料共用**（首版误定 0.30，会连带杀掉真简介）：
#        误剥的备注型      2% · 3% · 4%
#        真作品简介       26% · 27% · 28%   ← 中文比日文紧凑，占比天然偏低
#        真角色描述       27% · 29% · 33%   （原文本来就短，31–54 字）
#    ⚠️ 别照搬 F.3 标题补救的「≥30%」—— 那是给标题的，语料要松得多。
MIN_RATIO = 0.15

# ⚠️ 「是不是需要清洗」的入口阈值。**不要调到 0.03 以下** ——
#    中文简介里引用日文歌名/原名很常见，低阈值会把纯中文条目也拖进来。
DIRTY_MIN = 0.03


def kana_ratio(s: str) -> float:
    """假名字符占比。⚠️ 这是判断「是不是日文」的唯一可靠信号。"""
    return len(KANA.findall(s)) / max(len(s), 1)


def _ok(head: str, original: str) -> bool:
    """三道安全阀一起判：长度下限 · 语言 · 比例。任一不过就整条跳过。"""
    return (len(head) >= MIN_KEEP
            and kana_ratio(head) <= MAX_KANA
            and len(head) / max(len(original), 1) >= MIN_RATIO)


def strip_jp_tail(text: str) -> str:
    """剥掉尾部的日文原文段；不适用时**原样返回**。

    两种形态：
      ① 标记式  …中文…  [简介原文]  …日文…   → 从标记处截断
      ② 分块式  …中文…\\n\\n…日文…            → 按空行分块，丢尾部连续日文块

    ⚠️ **只剥尾部连续的日文块。** 中间夹的日文（歌名、角色原名、台词引用）
       是正文的一部分，剥掉会破坏语义 —— 实测角色 chunk 里 1,020 条
       「无标记混排」正是行内穿插，本函数一条都不动，交给翻译处理。
    """
    if not text or kana_ratio(text) <= DIRTY_MIN:
        return text

    # ── ① 标记式 ────────────────────────────────────────────
    m = MARK.search(text)
    if m:
        head = text[:m.start()].strip()
        if _ok(head, text):
            return head
        # ⚠️ 有标记但头部不合格 = 整条大概率是日文（标记前没实质中文），
        #    交给翻译，这里不动。
        return text

    # ── ② 分块式 ────────────────────────────────────────────
    blocks = [b for b in re.split(r"\n\s*\n", text) if b.strip()]
    if len(blocks) < 2:
        return text

    cut = len(blocks)
    while cut > 0 and kana_ratio(blocks[cut - 1]) > BLOCK_JP:
        cut -= 1
    if cut in (0, len(blocks)):     # 全是日文 / 尾部没有日文块
        return text

    head = "\n\n".join(blocks[:cut]).strip()
    return head if _ok(head, text) else text


def is_japanese(text: str, *, threshold: float = 0.20) -> bool:
    """整条是否为日文（清洗之后仍然是）—— 供翻译那一步筛选目标。

    ⚠️ **阈值 0.20 不是 0.03。** 实测 0.03 会把「中文里引用了日文原名」
       的条目误判成日文（《Fate/Zero》0.033 引用了「聖杯戦争」、
       《寒蝉鸣泣之时 礼》0.036 引用了「羞晒し编」）。
    ⚠️ 调用前应先过 strip_jp_tail() —— 否则中日混排条目会被误判成日文。
    """
    return kana_ratio(text) > threshold
