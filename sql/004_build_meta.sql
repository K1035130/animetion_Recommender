-- ============================================================
-- build_meta —— 派生数据的出处登记
-- ============================================================
-- ⚠️ **这张表存在的理由是「静默失效」这一类故障。**
--    换 embedding 模型 = 换向量空间的基 = 库里所有向量作废 —— 但**不报错**，
--    余弦照算、结果照排、看着完全正常，只是全是噪声（CLAUDE.md A.8）。
--    没有登记的话，这种事发生了没人会发现。
--
-- ⚠️ **为什么是表，不是像 jieba 那样写成代码常量。** 两者校验的东西不同：
--    · jieba 的 BUILD_FINGERPRINT 比的是**代码 vs 代码**（词表文件 vs 常量），
--      两者一起部署，硬编码在 server/main.py 里就够了。
--    · embedding 要比的是**代码 vs 数据**（当前 MODEL 常量 vs 库里那批向量
--      当初是谁算的）。数据在库里，登记也必须在库里，否则对不上号。
--
-- value 用 jsonb 而不是一个哈希字符串：指纹只能告诉你「不一致」，
-- 而排查时真正要的是「**哪里**不一致」。存完整描述符才能一眼看出
-- 是换了模型、改了维度，还是动了归一化策略。
CREATE TABLE IF NOT EXISTS build_meta (
    key         text        PRIMARY KEY,
    value       jsonb       NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE build_meta IS
    '派生数据的出处登记。key 一项对应一批派生数据，value 记录算它时的全部参数。';

