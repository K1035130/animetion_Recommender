-- ============================================================
-- staff_vec —— 制作公司 + (角色, 人名) 的 idf 加权向量
-- ============================================================
-- ⚠️ **它解决的是 P0 三类失败里的第 ① 类**：区分信息**在库里，但没进向量**。
--    第 8 节记的可复现案例：
--      大闹天宫  studios=['上海美术电影制片厂']  而 tag 只有 [玄幻, 小说改]
--      攻壳 SAC  studios=['Production I.G']      而 tag 只有 [科幻, 战斗, 漫画改]
--
--    ⚠️ 但 embedding 已经顺手解决了大闹天宫那个案例（现在最近邻是金猴降妖、
--       西游记）。所以 P1 现在要证明的是「**在 embedding 之上还能再加多少**」，
--       不是「比 tag 好多少」。第 5 周的报告框架要按这个改。
--
-- ⚠️ **第 ② 类失败（孤独摇滚 vs MyGO 的基调差异）这一列解决不了** ——
--    两者制作公司不同但都说明不了基调，只能靠 summary 的 embedding。
--    这两类论据在报告里必须分开讲，混在一起会让「为什么既要结构化特征
--    又要 embedding」这个设计选择失去说服力。

-- ============================================================
-- 为什么是 sparsevec 而不是 vector/halfvec
-- ============================================================
-- 词表 1,933 维（df>=8），但**每部作品平均只有 4.1 个非零值（0.2%）** ——
-- 比 tag_vec 的 1.24% 还稀疏一个量级。存 dense 的话：
--
--   vector(1933)   11,453 × 1933 × 4B = 88 MB
--   halfvec(1933)  同上 × 2B          = 44 MB
--   sparsevec      每行 ≈ 8 + 4×8 B   ≈ **640 KB**      ← 实测 2 个非零值占 29 B
--
-- ⚠️ 第 5 节的预算里 chunk 层只剩 355 MB，为 99.8% 的零付 44 MB 不可接受。
--    sparsevec 同样支持 `<=>` 余弦（pgvector 0.8.1 实测），
--    所以打分链路的形状完全不变 —— 仍是「pgvector 在库里算余弦」。
ALTER TABLE anime_profile ADD COLUMN IF NOT EXISTS staff_vec sparsevec(1933);

-- 无 staff/studio 数据的作品存 NULL，不存零向量 —— 与 tag_vec / vec 同一条纪律
-- （sql/002 第 30 行）：零向量与任何偏好向量的余弦都是 0，而偏好向量整体为负时
-- 0 反而**高于**所有负相关作品。实测 10,269 / 11,453 部有特征（90%）。

-- ============================================================
-- 不建索引
-- ============================================================
-- ⚠️ 与 tag_vec / vec 同样**不建 HNSW**：11k 行暴力算余弦是毫秒级，
--    且是精确检索。sparsevec 的 HNSW 还有额外限制，更不划算。

-- ============================================================
-- ⚠️ 词表顺序是这一列的生命线
-- ============================================================
-- 维度含义由 data/interim/staff_vocab.json 定义（scripts/build_staff_vectors.py
-- 产出并**入 git**，与 tag_vocab.json 同一条理由：它不是纯派生数据，
-- 而是「库里这批向量的每一维代表谁」的唯一记录）。
--
-- ⚠️ **词表一变，库里所有 staff_vec 立刻失效且不报错** —— 维度还是 1933，
--    余弦照算，只是每一维的含义全错了。靠 build_meta 的 'staff_vec' 指纹兜底。
--
-- ⚠️ idf 依赖全库词频，因此**只能全量重算，不能逐行增量更新**。
--    第 6 周季度同步加入新作品后必须整列重跑。

